public class arrays {
    public static void main(String[] args){
        int arr[] = {10,20,30,40,50};
        // index->10->0,1,2,3,4
        System.out.println(arr[1]);
        // length of array ->5

        // 2d array
        int [][]nums = {
            {10,20,30},
            {40,50,60}
        };

        System.out.println(nums[0][0]);
        System.out.println(nums[1][1]);
    }
}
